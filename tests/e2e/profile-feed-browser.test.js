import test from 'node:test';
import assert from 'node:assert/strict';
import {createBrowserHarness,createBackendFixture,POST_ID,PROFILE} from './browser-harness.js';

let harness;
test.before(async()=>{harness=await createBrowserHarness();});
test.after(async()=>{await harness?.close();});
const picture='public/icons/icon-192.png';

async function openProfileEditor(page){
  await page.locator('.avatar-btn').click();
  await page.locator('[data-action="edit-profile"]').click();
  await page.waitForSelector('#profileForm');
}
function assertClean({errors,fixture}){assert.deepEqual(errors,[]);assert.deepEqual(fixture.failures,[]);}

test('profile text/preferences and immutable avatar/banner uploads survive replace, reload and removal',async t=>{
  const scenario=await harness.scenario(t);
  const {page,fixture}=scenario;
  await openProfileEditor(page);
  await page.locator('#profileForm [name="nickname"]').fill('Edited Author');
  await page.locator('#profileForm [name="bio"]').fill('Profile changes must survive a browser reload.');
  await page.locator('#profileForm [name="currentStatus"]').fill('Проверено в браузере');
  await page.locator('#profileForm label:has(>input[name="wantedGenres"][value="1"])').click();
  assert.equal(await page.locator('#profileForm [name="wantedGenres"][value="1"]').isChecked(),true);
  await page.locator('#profileAvatarUpload').setInputFiles(picture);
  await page.waitForFunction(()=>document.querySelector('#profileMediaStatus').textContent==='Изображение сохранено');
  const firstAvatar=fixture.tables.lit_profiles[0].avatar_path;
  assert.match(firstAvatar,/\/avatar\/[a-f0-9-]+\.webp$/);
  assert.ok(fixture.objects.has(`lit-avatars/${firstAvatar}`));
  await page.locator('#profileAvatarUpload').setInputFiles(picture);
  await page.waitForFunction(()=>document.querySelector('#profileMediaStatus').textContent==='Изображение сохранено');
  const secondAvatar=fixture.tables.lit_profiles[0].avatar_path;
  assert.notEqual(secondAvatar,firstAvatar);
  assert.equal(fixture.objects.has(`lit-avatars/${firstAvatar}`),false);
  assert.ok(fixture.objects.has(`lit-avatars/${secondAvatar}`));
  await page.locator('#profileBannerUpload').setInputFiles(picture);
  await page.waitForFunction(()=>document.querySelector('#profileMediaStatus').textContent==='Изображение сохранено');
  const banner=fixture.tables.lit_profiles[0].banner_path;
  assert.match(banner,/\/banner\/[a-f0-9-]+\.webp$/);
  await page.locator('#profileForm button[type="submit"]').click();
  await page.waitForSelector('#profileForm',{state:'detached'});
  assert.match(await page.locator('.profile-main h1').innerText(),/Edited Author/);
  assert.ok(fixture.requests.some(request=>request.pathname==='/rest/v1/rpc/lit_save_my_profile'));
  await page.reload();
  await page.waitForSelector('.app-shell');
  await page.locator('.avatar-btn').click();
  await page.waitForSelector('.profile-avatar-v2 img');
  const avatarSrc=await page.locator('.profile-avatar-v2 img').getAttribute('src');
  assert.ok(avatarSrc.endsWith(secondAvatar));
  assert.ok((await page.locator('.profile-banner').getAttribute('style')).includes(banner));
  assert.match(await page.locator('.profile-content').innerText(),/Profile changes must survive/);
  assert.match(await page.locator('.profile-content').innerText(),/Фэнтези/);
  await page.locator('[data-action="edit-profile"]').click();
  await page.locator('#profileAvatarRemove').click();
  await page.waitForFunction(()=>document.querySelector('#profileMediaStatus').textContent==='Изображение удалено');
  await page.locator('#profileBannerRemove').click();
  await page.waitForFunction(()=>document.querySelector('#profileMediaStatus').textContent==='Изображение удалено');
  assert.equal(fixture.tables.lit_profiles[0].avatar_path,null);
  assert.equal(fixture.tables.lit_profiles[0].banner_path,null);
  assert.equal(fixture.objects.size,0);
  await page.reload();
  await page.waitForSelector('.app-shell');
  await page.locator('.avatar-btn').click();
  await page.waitForSelector('.profile-main');
  assert.equal(await page.locator('.profile-avatar-v2 img').count(),0);
  assert.equal(await page.locator('.profile-banner').getAttribute('style'),'');
  assertClean(scenario);
});

test('feed creates image posts, persists likes, comments and comment reactions through HTTP fixtures',async t=>{
  const scenario=await harness.scenario(t);
  const {page,fixture}=scenario;
  await page.locator('[data-action="open-post"]').first().click();
  await page.locator('#postForm [name="text"]').fill('Image post browser regression');
  await page.locator('#postForm [name="media"]').setInputFiles(picture);
  await page.locator('#postForm button').click();
  await page.waitForSelector('#postForm',{state:'detached'});
  const created=fixture.tables.lit_posts.find(post=>post.body==='Image post browser regression');
  assert.ok(created);
  const card=page.locator(`.post[data-post-id="${created.id}"]`);
  await card.waitFor();
  assert.equal(await card.locator('img.post-image,.post-media img,img').count()>0,true);
  assert.ok(fixture.tables.lit_post_media.some(media=>media.post_id===created.id));
  await page.locator(`[data-action="like-post"][data-id="cloud:${POST_ID}"]`).click();
  await page.waitForFunction(()=>document.querySelector('[data-action="like-post"]')?.textContent.includes('1'));
  assert.equal(fixture.tables.lit_post_reactions.length,1);
  await page.locator(`[data-action="open-post-comments"][data-id="cloud:${POST_ID}"]`).click();
  await page.locator('#postCommentForm [name="text"]').fill('Comment from the browser regression.');
  await page.locator('#postCommentForm button').click();
  await page.waitForSelector('.post-comment');
  assert.match(await page.locator('.post-comment').innerText(),/Comment from the browser regression/);
  await page.locator('.post-comment [data-action="react-post-comment"][data-kind="helpful"]').click();
  await page.waitForFunction(()=>document.querySelector('.post-comment [data-kind="helpful"]')?.textContent.includes('1'));
  assert.equal(fixture.tables.lit_comment_reactions[0].reaction,'helpful');
  assertClean(scenario);
});

test('messenger opens a direct chat, sends a message and creates a persistent project group',async t=>{
  const fixture=createBackendFixture();
  const peer={...PROFILE,id:'22222222-2222-4222-8222-222222222222',username:'peer-reader',nickname:'Peer Reader'};
  fixture.tables.lit_profiles.push(peer);
  const scenario=await harness.scenario(t,{fixture});
  const {page}=scenario;
  await page.locator('.chat-edge-toggle').click();
  await page.locator('#friendForm [name="username"]').fill('@peer-reader');
  await page.locator('#friendForm button').click();
  await page.waitForSelector('.drawer-chat .thread-message-form');
  assert.match(await page.locator('.drawer-chat-head').innerText(),/Peer Reader/);
  await page.locator('.drawer-chat .thread-message-form [name="message"]').fill('Direct browser message');
  await page.locator('.drawer-chat .thread-message-form button').click();
  await page.waitForFunction(()=>document.querySelector('.drawer-messages')?.textContent.includes('Direct browser message'));
  assert.equal(fixture.tables.lit_messages[0].body,'Direct browser message');
  await page.locator('.drawer-tabs [data-tab="groups"]').click();
  await page.locator('#chat-drawer [data-action="new-collab-group"]').click();
  await page.locator('#collabGroupForm [name="name"]').fill('Browser Project Group');
  await page.locator('#collabGroupForm label:has(>input[name="members"])').click();
  await page.locator('#collabGroupForm button').click();
  await page.waitForSelector('#collabGroupForm',{state:'detached'});
  const group=fixture.tables.lit_conversations.find(conversation=>conversation.title==='Browser Project Group');
  assert.ok(group);
  assert.equal(fixture.tables.lit_conversation_members.filter(member=>member.conversation_id===group.id).length,2);
  await page.waitForSelector('.drawer-chat .thread-message-form');
  await page.locator('.drawer-chat .thread-message-form [name="message"]').fill('Group browser message');
  await page.locator('.drawer-chat .thread-message-form button').click();
  await page.waitForFunction(()=>document.querySelector('.drawer-messages')?.textContent.includes('Group browser message'));
  await page.reload();
  await page.waitForSelector('.app-shell');
  await page.locator('.chat-edge-toggle').click();
  await page.locator('.drawer-tabs [data-tab="groups"]').click();
  assert.match(await page.locator('.drawer-thread-list').innerText(),/Browser Project Group/);
  assertClean(scenario);
});
